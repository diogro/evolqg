test_that("SRD returns correct results", {
  local_seed(1)
  cov.matrix.1 <- cov(matrix(rnorm(30*10), 30, 10))
  cov.matrix.2 <- cov(matrix(rnorm(30*10), 30, 10))
  srd.output <- SRD(cov.matrix.1, cov.matrix.2)
  expect_s3_class(srd.output, "SRD")
  expect_equal(names(srd.output), c("output", "pc1", "model"))
  expect_equal(names(srd.output[[3]]), c("quantiles", "interval", "code"))
  expect_equal(dim(srd.output[[1]]), c(10, 6))
  expect_length(srd.output[[2]], 10)
  expect_length(srd.output[[3]], 3)
  expect_true(is.matrix(srd.output[[1]]))
  expect_type(srd.output[[2]], "double")
  expect_type(srd.output[[3]], "list")
  expect_true(all(srd.output[[1]][, 1] > -1 & srd.output[[1]][, 1] < 1))
  expect_true(all(srd.output[[1]][, 2] > -1 & srd.output[[1]][, 2] < 1))
  expect_true(all(srd.output[[1]][, 3] > -1 & srd.output[[1]][, 3] < 1))
  expect_true(all(srd.output[[1]][, 4] > 0 & srd.output[[1]][, 4] < 1))
  expect_equal(mean(srd.output[[1]][, 5]), 0)
  expect_equal(mean(srd.output[[1]][, 6]), 0)
  expect_equal(mean(srd.output[[2]]), 0)
  expect_equal(as.numeric(srd.output[[2]] < srd.output[[3]][[2]]), srd.output[[3]][[3]])
})

test_that("SRD matches the direct per-iteration definition", {
  local_seed(2)
  cx <- cov(matrix(rnorm(30*5), 30, 5)); cy <- cov(matrix(rnorm(30*5), 30, 5))
  rownames(cx) <- letters[1:5]
  iterations <- 30
  local_seed(3)
  out <- SRD(cx, cy, iterations = iterations)
  local_seed(3)
  beta <- apply(matrix(rnorm(5*iterations), 5, iterations), 2, Normalize)
  r2s <- sapply(seq_len(iterations), function(i) {
    dz1 <- apply(cx %*% diag(beta[, i]), 1, Normalize)
    dz2 <- apply(cy %*% diag(beta[, i]), 1, Normalize)
    colSums(dz1 * dz2)
  })
  expect_equal(unname(out$output[, "ARC"]), unname(rowMeans(r2s)))
  expect_equal(unname(out$output[, "SD"]), unname(apply(r2s, 1, sd)))
  expect_equal(rownames(out$output), letters[1:5])
})

test_that("SRD works with few iterations", {
  local_seed(4)
  m <- RandomMatrix(10, 2)
  out <- SRD(m[[1]], m[[2]], iterations = 20)
  expect_s3_class(out, "SRD")
  expect_true(all(is.finite(out$output)))
  expect_error(SRD(m[[1]], m[[2]], iterations = 10), "Iterations must be larger")
})

test_that("SRD returns correct results on lists", {
  m.list <- RandomMatrix(10, 4)
  local_seed(42, "3.5.0")
  srd.all <- SRD(m.list, iterations = 100)
  local_seed(42, "3.5.0")
  one.and.two <- srd.all[1, 2][[1]]
  one.and.two.default <- SRD(m.list[[2]], m.list[[1]], iterations = 100)
  expect_equal(one.and.two, one.and.two.default, ignore_attr = TRUE)
  expect_true(is.matrix(srd.all))
  expect_true(isSymmetric(srd.all))
  expect_equal(dim(srd.all), c(4, 4))
})

test_that("SRD.list handles one matrix and cov.y", {
  local_seed(5)
  m.list <- RandomMatrix(6, 3)
  expect_error(SRD(m.list[1]), "at least two")
  expect_warning(out <- SRD(m.list, cov.y = m.list[[1]], iterations = 20), "cov.y")
  expect_equal(dim(out), c(3, 3))
})

