test_that("PCScoreScorrelation returns resonable results", {
  local_seed(1)
  means <- array(rnorm(40*10), c(10, 40))
  cov.matrix <- RandomMatrix(40, 1, 1, 10)
  taxons <- letters[1:10]
  means.list <- alply(means, 1)
  names(means.list) <- taxons
  test.array <- PCScoreCorrelation(means, cov.matrix, taxons, FALSE)
  test.list <- PCScoreCorrelation(means.list, cov.matrix, taxons, FALSE)
  expect_equal(abs(test.array), abs(test.list))
  test.array.plots <- PCScoreCorrelation(means, cov.matrix, taxons, TRUE)
  test.list.plots <- PCScoreCorrelation(means.list, cov.matrix, taxons, TRUE)
  expect_type(test.array.plots, "list")
  expect_true(is.matrix(test.array.plots[[1]]))
  expect_type(test.array.plots[[2]], "list")
  expect_equal(length(test.array.plots[[2]]), 36)
  expect_s3_class(test.array.plots[[2]][[1]], "ggplot")
  expect_no_error(ggplot2::ggplot_build(test.array.plots[[2]][[1]]))
  expect_equal(names(test.array.plots), c("correlation_p.value", "plots"))
  expect_equal(dim(test.array), c(9, 9))
})

test_that("PCScoreCorrelation checks the length of taxons", {
  local_seed(2)
  means <- array(rnorm(40*10), c(10, 40))
  cov.matrix <- RandomMatrix(40, 1, 1, 10)
  expect_error(PCScoreCorrelation(means, cov.matrix, letters[1:5]), "length of taxons")
  expect_error(PCScoreCorrelation(means, cov.matrix, letters[1:12]), "length of taxons")
  expect_equal(dim(PCScoreCorrelation(means, cov.matrix)), c(9, 9))
})
